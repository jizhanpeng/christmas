(function(app){
  'use strict';

  app.createShaders=function(){
    var config=app.config,intro=config.intro;
    function number(value){ return value.toFixed(3); }

    var vertexSource=[
      'precision highp float;',
      'attribute vec3 aPosition;',
      'attribute vec3 aScatter;',
      'attribute vec3 aColor;',
      'attribute vec4 aParams;',
      'attribute vec4 aMisc;',
      'uniform float uTime;',
      'uniform float uIntro;',
      'uniform float uYaw;',
      'uniform float uPitch;',
      'uniform float uScale;',
      'uniform float uOffsetX;',
      'uniform float uOffsetY;',
      'uniform float uAspect;',
      'uniform float uDpr;',
      'uniform float uRadius;',
      'uniform float uBurstAge;',
      'uniform float uPulse;',
      'uniform vec2 uPointerWorld;',
      'uniform float uPointerForce;',
      'varying vec3 vColor;',
      'varying float vAlpha;',
      'varying float vSoft;',
      'varying float vHero;',
      'varying float vFlash;',
      'varying float vIntroBoost;',
      'const float TREE_H='+number(config.treeHeight)+';',
      'const float HEART_Y='+number(config.heartY)+';',
      'const float CAMERA_D='+number(config.cameraDistance)+';',
      'const float PI=3.14159265359;',
      'vec3 rotateY(vec3 p,float a){',
      '  float c=cos(a),s=sin(a);',
      '  return vec3(p.x*c-p.z*s,p.y,p.x*s+p.z*c);',
      '}',
      'float smooth01(float v){',
      '  v=clamp(v,0.0,1.0); return v*v*(3.0-2.0*v);',
      '}',
      'float easeOut(float v){',
      '  v=clamp(v,0.0,1.0); return 1.0-pow(1.0-v,3.0);',
      '}',
      'float worldYAtNdc(float ndc,float z){',
      '  float k=(ndc-uOffsetY)/uScale;',
      '  float cp=cos(uPitch),sp=sin(uPitch);',
      '  return (k*CAMERA_D+z*(sp-k*cp))/(cp+k*sp);',
      '}',
      'float offscreenY(float z){',
      '  return worldYAtNdc(1.25,z);',
      '}',
      'float bellSwing(float index){',
      '  float age=max(0.0,uIntro-('+number(intro.bellDropEnd)+'-0.320+index*0.160));',
      '  return sin(age*4.4+index*1.9)*exp(-age*0.95)*smoothstep(0.0,0.12,age)*0.42;',
      '}',
      'vec3 bellCenter(vec3 anchor,float index){',
      '  float drop=easeOut((uIntro-index*0.160)/('+number(intro.bellDropEnd)+'-0.320));',
      '  float topY=offscreenY(anchor.z);',
      '  return anchor+vec3(bellSwing(index),(1.0-drop)*(topY+0.8-anchor.y),0.0);',
      '}',
      // 由向量势的旋度得到连续流场，避免逐帧随机跳动和局部聚集
      'vec3 curlField(vec3 p,float t){',
      '  float x=p.x,y=p.y,z=p.z;',
      '  return vec3(',
      '    -0.7*sin(x*1.2+t*0.15)*sin(y*0.7)-1.1*cos(z*1.1+t*0.17)*cos(x*0.8),',
      '    -0.9*sin(y*1.3+t*0.20)*sin(z*0.9)-1.2*cos(x*1.2+t*0.15)*cos(y*0.7),',
      '    -0.8*sin(z*1.1+t*0.17)*sin(x*0.8)-1.3*cos(y*1.3+t*0.20)*cos(z*0.9));',
      '}',
      'void main(){',
      '  float kind=aMisc.w;',
      '  float seed=aMisc.z;',
      '  vec3 p=aPosition;',
      '  float endFade=1.0;',
      '  float introHead=0.0;',
      '  float heightNorm=clamp(aPosition.y/TREE_H,0.0,1.0);',
      '  if(kind>0.5&&kind<1.5){',
      '    float u=fract(aParams.x+uTime*0.026);',
      '    float r=uRadius*pow(1.0-u,1.02)+aParams.z;',
      '    float theta=u*35.185837+uYaw+aParams.y;',
      '    p=vec3(cos(theta)*r,u*TREE_H+aParams.w,sin(theta)*r);',
      '    heightNorm=u;',
      '    endFade=smoothstep(0.0,0.025,u)*(1.0-smoothstep(0.955,1.0,u));',
      '    endFade*=0.48+0.52*(1.0-u);',
      '  }else if(kind<0.5||(kind>2.5&&kind<3.5)){',
      '    p=rotateY(p,uYaw);',
      '  }else if(kind>10.5){',
      '    if(kind<11.5){',
      '      float snowTop=offscreenY(p.z);',
      '      float snowBottom=worldYAtNdc(-1.22,p.z);',
      '      p.y=snowTop-mod(snowTop-aPosition.y+uTime*aParams.x,snowTop-snowBottom);',
      '      p.x+=sin(uTime*(0.16+seed*0.12)+aParams.y)*aParams.z;',
      '      endFade=smoothstep(snowBottom,snowBottom+0.35,p.y)*(1.0-smoothstep(snowTop-0.35,snowTop,p.y));',
      '    }else{',
      '      float direction=mod(aParams.y,2.0)<1.0?1.0:-1.0;',
      '      p=rotateY(p,direction*uTime*(0.055-aParams.y*0.010));',
      '      float breathe=1.0+sin(uTime*0.65+aParams.z)*0.012;',
      '      p.xz*=breathe;',
      '      endFade=0.50+0.50*(0.5+0.5*sin(aParams.x*2.0-uTime*0.85+aParams.z));',
      '    }',
      '  }else if(kind>8.5){',
      '    vec3 center=bellCenter(aParams.xyz,aParams.w);',
      '    float angle=bellSwing(aParams.w)*0.65;',
      '    float cs=cos(angle),ss=sin(angle);',
      '    if(kind<9.5){',
      '      vec3 q=p-aParams.xyz;',
      '      p=center+vec3(q.x*cs-q.y*ss,q.x*ss+q.y*cs,q.z);',
      '      float scatter=smooth01((uIntro-'+number(intro.bellScatterStart)+')/('+number(intro.prelude)+'-'+number(intro.bellScatterStart)+'));',
      '      p=mix(p,aScatter,scatter);',
      '      float arc=sin(scatter*PI);',
      '      p+=vec3(sin(seed*40.0+scatter*6.0)*0.34,0.28+seed*0.32,cos(seed*31.0+scatter*5.0)*0.28)*arc;',
      '      endFade=(1.0-scatter*0.55)*(1.0-smoothstep('+number(intro.prelude)+','+number(intro.bellFadeEnd)+',uIntro));',
      '    }else{',
      '      vec3 bottom=center+vec3(-ss*aPosition.y,cs*aPosition.y,0.0);',
      '      vec3 top=vec3(aParams.x,offscreenY(aParams.z),aParams.z);',
      '      p=mix(bottom,top,aPosition.x);',
      '      endFade=1.0-smoothstep('+number(intro.bellScatterStart)+','+number(intro.lineFadeEnd)+',uIntro);',
      '    }',
      '  }else if(kind>7.5){',
      '    float head=clamp((uIntro-'+number(intro.prelude)+')/('+number(intro.rise)+'-'+number(intro.prelude)+'),0.0,1.0);',
      '    float collapse=smoothstep('+number(intro.rise)+','+number(intro.collapseEnd)+',uIntro);',
      '    float pathU=max(0.0,head-aParams.y*(1.0-collapse));',
      '    float theta=pathU*PI*4.4+aParams.x*PI+aParams.w;',
      '    float trailRadius=uRadius*0.72*pow(1.0-pathU,0.82)*(1.0+aParams.z);',
      '    p=vec3(cos(theta)*trailRadius,pathU*TREE_H,sin(theta)*trailRadius);',
      '    introHead=exp(-aParams.y*32.0);',
      '    endFade=smoothstep(0.0,0.025,pathU)*(1.0-smoothstep('+number(intro.holdEnd)+','+number(intro.fadeEnd)+',uIntro));',
      '  }else if(kind>6.5){',
      '    float age=fract(uTime*0.14+aParams.w);',
      '    float progress=clamp((age-0.16)/0.84,0.0,1.0);',
      '    float expansion=1.0-pow(1.0-progress,3.0);',
      '    p=aPosition+aParams.xyz*expansion;',
      '    p.y-=progress*progress*0.24;',
      '    endFade=smoothstep(0.16,0.20,age)*(1.0-smoothstep(0.64,1.0,age));',
      '  }else if(kind>4.5){',
      '    if(kind<5.5){',
      '      vec3 q=p-aParams.xyz;',
      '      float swing=sin(uTime*0.85+seed*6.283)*0.08;',
      '      float cs=cos(swing),ss=sin(swing);',
      '      p=aParams.xyz+vec3(q.x*cs-q.y*ss,q.x*ss+q.y*cs,q.z);',
      '    }',
      '    p=rotateY(p,uYaw);',
      '  }else if(kind>3.5){',
      '    p=rotateY(p,uYaw*0.06);',
      '    p.y=mod(p.y+uTime*(0.018+seed*0.025),TREE_H+1.2);',
      '    p.x+=sin(uTime*0.18+seed*19.0)*0.08;',
      '  }',
      '  if(kind>1.5&&kind<2.5){',
      '    float breathe=1.0+0.035*sin(uTime*1.25);',
      '    p.x*=breathe;',
      '    p.y=HEART_Y+(p.y-HEART_Y)*breathe;',
      '  }',
      '  float treeMask=(kind<3.5||(kind>4.5&&kind<6.5))?1.0:0.0;',
      '  float reveal=smooth01((uIntro-'+number(intro.revealStart)+')/'+number(intro.revealDuration)+');',
      '  float revealY=mix(HEART_Y+0.34,-0.35,reveal);',
      '  float introVisibility=smoothstep(revealY-0.22,revealY+0.22,aPosition.y);',
      '  introVisibility=mix(1.0,introVisibility,treeMask);',
      '  if(kind>6.5&&kind<7.5) introVisibility=smoothstep('+number(intro.fireworksStart)+','+number(intro.fireworksEnd)+',uIntro);',
      '  if(kind>11.5) introVisibility=smoothstep('+number(intro.revealStart+0.25)+','+number(intro.revealStart+1.45)+',uIntro);',
      '  float flowAmp=0.035;',
      '  if(kind>0.5&&kind<1.5) flowAmp=0.018;',
      '  if(kind>1.5&&kind<2.5) flowAmp=0.006;',
      '  if(kind>2.5&&kind<3.5) flowAmp=0.055;',
      '  if(kind>3.5&&kind<4.5) flowAmp=0.035;',
      '  if(kind>4.5) flowAmp=0.008;',
      '  if(kind>6.5) flowAmp=0.004;',
      '  if(kind>7.5) flowAmp=0.002;',
      '  p+=curlField(p,uTime)*flowAmp;',
      '  vec2 away=p.xy-uPointerWorld;',
      '  float pointerForce=(1.0-smoothstep(0.0,0.85,length(away)))*uPointerForce*treeMask;',
      '  p.xy+=normalize(away+vec2(0.0001))*pointerForce*0.32;',
      '  p.z+=pointerForce*0.24;',
      '  float delay=seed*0.20+(1.0-heightNorm)*0.05;',
      '  if(kind>1.5&&kind<2.5) delay+=0.16;',
      '  float age=max(0.0,uBurstAge-delay);',
      '  float burst=0.0,visibility=1.0;',
      '  if(uBurstAge>=0.0){',
      '    if(age<0.85){',
      '      burst=easeOut(age/0.85); visibility=1.0-0.97*smooth01(age/0.85);',
      '    }else if(age<1.25){',
      '      burst=1.0; visibility=0.03;',
      '    }else if(age<3.75){',
      '      float gather=(age-1.25)/2.5;',
      '      burst=1.0-smooth01(gather); visibility=0.03+0.97*smooth01(gather);',
      '    }',
      '  }',
      '  burst*=treeMask;',
      '  visibility=mix(1.0,visibility,treeMask);',
      '  p=mix(p,aScatter,burst);',
      '  float arc=sin(burst*PI);',
      '  p=rotateY(p,arc*(0.7+seed*0.9));',
      '  p.x+=sin(seed*31.0+uTime*2.0)*arc*0.28;',
      '  p.y+=cos(seed*27.0+uTime*1.7)*arc*0.22;',
      '  float lightPulse=0.0;',
      '  if(uPulse>=0.0){',
      '    float pulsePosition=uPulse*1.15-0.05;',
      '    lightPulse=exp(-pow((heightNorm-pulsePosition)*16.0,2.0));',
      '    lightPulse*=(1.0-smoothstep(0.82,1.0,uPulse))*treeMask;',
      '  }',
      '  float cp=cos(uPitch),sp=sin(uPitch);',
      '  float viewY=p.y*cp-p.z*sp;',
      '  float viewZ=p.y*sp+p.z*cp;',
      '  float depth=max(1.0,CAMERA_D-viewZ);',
      '  gl_Position=vec4(',
      '    p.x*uScale/uAspect+uOffsetX*depth,',
      '    viewY*uScale+uOffsetY*depth,',
      '    0.0,depth);',
      '  float perspective=CAMERA_D/depth;',
      '  gl_PointSize=clamp(aMisc.x*uDpr*perspective*(1.0+introHead*'+number(intro.headSize)+')*(1.0+burst*0.35+lightPulse*0.45),1.0,'+number(intro.maxPointSize)+');',
      '  float front=clamp((viewZ+uRadius)/(2.0*uRadius),0.0,1.0);',
      '  float depthLight=mix(0.32,1.0,front);',
      '  if(kind>1.5&&kind<2.5) depthLight=0.9;',
      '  if(kind>6.5) depthLight=0.82;',
      '  if(kind>7.5) depthLight=0.95;',
      '  if(kind>10.5&&kind<11.5) depthLight=0.35+0.55*clamp((aPosition.z+3.5)/6.5,0.0,1.0);',
      '  if(kind>11.5) depthLight=0.45+0.45*front;',
      '  float twinkle=0.80+0.20*sin(uTime*(0.7+seed)+seed*24.0);',
      '  vAlpha=min(1.0,(aMisc.y*depthLight*twinkle*endFade*visibility*1.65+lightPulse*0.045)*introVisibility);',
      '  vColor=mix(aColor,vec3(0.85,0.92,1.0),clamp(lightPulse*0.45,0.0,1.0));',
      '  vSoft=(kind>2.5&&kind<3.5)?1.0:0.0;',
      '  if(kind>10.5&&kind<11.5) vSoft=0.28;',
      '  vHero=(kind>5.5&&kind<6.5)?1.0:0.0;',
      '  vFlash=(kind>7.5&&kind<8.5)?smoothstep('+number(intro.rise)+','+number(intro.collapseEnd)+',uIntro):0.0;',
      '  vIntroBoost=1.0+introHead*'+number(intro.headBrightness)+';',
      '}'
    ].join('\n');

    var fragmentSource=[
      'precision highp float;',
      'varying vec3 vColor;',
      'varying float vAlpha;',
      'varying float vSoft;',
      'varying float vHero;',
      'varying float vFlash;',
      'varying float vIntroBoost;',
      'void main(){',
      '  vec2 uv=gl_PointCoord-vec2(0.5);',
      '  float d=length(uv)*2.0;',
      '  if(d>1.0) discard;',
      '  float halo=1.0-smoothstep(0.05,1.0,d);',
      '  float core=1.0-smoothstep(0.02,0.32,d);',
      '  float shape=mix(core*0.82+halo*0.30,halo*0.32,vSoft);',
      '  vec2 q=abs(uv);',
      '  float rayV=(1.0-smoothstep(0.0,0.025,q.x))*(1.0-smoothstep(0.08,0.5,q.y));',
      '  float rayH=(1.0-smoothstep(0.0,0.025,q.y))*(1.0-smoothstep(0.08,0.5,q.x));',
      '  float star=max(core,max(rayV,rayH)*0.55);',
      '  shape=mix(shape,star,vHero);',
      '  float flashAngle=atan(uv.y,uv.x);',
      '  float flashReach=0.22+0.24*(0.5+0.5*sin(flashAngle*5.0+0.8));',
      '  float flashRays=pow(abs(cos(flashAngle*3.0+0.35)),28.0);',
      '  float flashShape=flashRays*(1.0-smoothstep(0.015,flashReach,length(uv)));',
      '  shape=mix(shape,flashShape,vFlash);',
      '  float alpha=shape*vAlpha;',
      '  gl_FragColor=vec4(vColor*(0.82+core*0.75)*vIntroBoost,alpha);',
      '}'
    ].join('\n');

    return {vertexSource:vertexSource,fragmentSource:fragmentSource};
  };
})(window.ChristmasScene=window.ChristmasScene||{});
